#!/bin/bash
# MASTER SWITCH for the file features. Usage: set_files_mode.sh on|off|status
#   off = clean site: no Download/Stream anywhere, /tgstream answers 410 to the public (this server's own tools still work).
#   on  = old behaviour.
# Changes /var/lib/trendimovies/site_mode.json (read live by the website) and /etc/nginx/snippets/files-mode.conf, then reloads nginx.
set -u
MODE_FILE=/var/lib/trendimovies/site_mode.json
SNIP=/etc/nginx/snippets/files-mode.conf
case "${1:-status}" in
  status) cat "$MODE_FILE"; echo; cat "$SNIP"; exit 0 ;;
  off) ON=false
       BODY='# GENERATED by set_files_mode.sh (files OFF): the public gets 410 on file addresses; this server itself (127.0.0.1 / own IP) is still allowed for internal tools.
set $tm_files_closed 1;
if ($remote_addr = 127.0.0.1) { set $tm_files_closed 0; }
if ($remote_addr = 57.131.157.245) { set $tm_files_closed 0; }
if ($tm_files_closed) { return 410; }' ;;
  on)  ON=true
       BODY='# GENERATED by set_files_mode.sh (files ON): nothing blocked here.' ;;
  *) echo "usage: $0 on|off|status"; exit 1 ;;
esac
OLD=$(cat "$SNIP" 2>/dev/null || true)
printf '%s\n' "$BODY" > "$SNIP"
if ! nginx -t >/dev/null 2>&1; then
  printf '%s\n' "$OLD" > "$SNIP"; echo "nginx test FAILED, nothing changed"; exit 1
fi
printf '{"files_enabled": %s}\n' "$ON" > "$MODE_FILE"
systemctl reload nginx && echo "files_enabled=$ON, nginx reloaded"
