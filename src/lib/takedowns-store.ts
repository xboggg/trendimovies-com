// One place for all takedown logic. The list lives in a plain file (TAKEDOWN_FILE) so that the website page,
// the nginx block and the link engine (trendimovies_cron.py) all read the SAME list, with no rebuild or code change.
import { readFileSync, writeFileSync, existsSync, mkdirSync, renameSync, statSync, copyFileSync } from 'fs';
import { execFile } from 'child_process';
import { dirname } from 'path';

export const TAKEDOWN_FILE = '/var/lib/trendimovies/takedowns.json';
export const NGINX_SNIPPET = '/etc/nginx/snippets/takedowns.conf';
const DB = 'trendimovies';

export type TakedownEntry = {
  tmdb_id: number;
  title: string;
  year: number | null;
  key: string;          // lower-case title used by the link engine (letters/digits/spaces only)
  files: string[];      // Telegram file ids that must answer 410
  note: string;         // who reported it
  added: string;        // ISO date
};

// Same cleaning the link engine uses for its keys: lower case, only letters/digits, single spaces.
export function titleKey(title: string): string {
  return (title || '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
}

export function readTakedowns(): TakedownEntry[] {
  try {
    if (!existsSync(TAKEDOWN_FILE)) return [];
    const d = JSON.parse(readFileSync(TAKEDOWN_FILE, 'utf-8'));
    return Array.isArray(d) ? d : [];
  } catch {
    return [];
  }
}

function writeTakedowns(list: TakedownEntry[]) {
  mkdirSync(dirname(TAKEDOWN_FILE), { recursive: true });
  if (existsSync(TAKEDOWN_FILE)) copyFileSync(TAKEDOWN_FILE, TAKEDOWN_FILE + '.prev');
  const tmp = TAKEDOWN_FILE + '.tmp';
  writeFileSync(tmp, JSON.stringify(list, null, 2) + '\n', 'utf-8');
  renameSync(tmp, TAKEDOWN_FILE);
}

// cached read for the movie page (re-reads only when the file changes)
let cache: { mtime: number; ids: Set<number> } | null = null;
export function takenDownIds(): Set<number> {
  try {
    const m = existsSync(TAKEDOWN_FILE) ? statSync(TAKEDOWN_FILE).mtimeMs : 0;
    if (cache && cache.mtime === m) return cache.ids;
    cache = { mtime: m, ids: new Set(readTakedowns().map((e) => Number(e.tmdb_id))) };
    return cache.ids;
  } catch {
    return cache ? cache.ids : new Set();
  }
}

function run(cmd: string, args: string[], timeoutMs = 30000): Promise<{ ok: boolean; out: string; err: string }> {
  return new Promise((resolve) => {
    execFile(cmd, args, { timeout: timeoutMs, maxBuffer: 4 * 1024 * 1024 }, (e, stdout, stderr) => {
      resolve({ ok: !e, out: (stdout || '').toString(), err: ((stderr || '') + (e ? ' ' + e.message : '')).toString() });
    });
  });
}

// SQL as the postgres user. Only whole numbers are ever put into the SQL text.
export async function sql(statement: string): Promise<{ ok: boolean; rows: string[][]; err: string }> {
  const r = await run('sudo', ['-n', '-u', 'postgres', 'psql', '-d', DB, '-At', '-F', '\t', '-v', 'ON_ERROR_STOP=1', '-c', statement]);
  const rows = r.out.split('\n').filter((l) => l.length > 0 && !/^(UPDATE|INSERT|DELETE) \d+$/.test(l)).map((l) => l.split('\t'));
  return { ok: r.ok, rows, err: r.err.trim() };
}

// Rebuild the nginx block from the list and reload nginx. If nginx rejects the file, the old one is put back.
export async function applyNginx(list: TakedownEntry[]): Promise<{ ok: boolean; err: string }> {
  const ids = Array.from(new Set(list.flatMap((e) => e.files || []).filter((f) => /^\d+$/.test(f))));
  let body = '# GENERATED by the admin Takedowns page. Do not edit by hand; edit /var/lib/trendimovies/takedowns.json or use /admin/takedowns.\n';
  if (ids.length) {
    body += `if ($uri ~ "/(${ids.join('|')})(/|$)") {\n    return 410;\n}\n`;
  }
  const had = existsSync(NGINX_SNIPPET);
  const old = had ? readFileSync(NGINX_SNIPPET, 'utf-8') : '';
  writeFileSync(NGINX_SNIPPET, body, 'utf-8');
  const t = await run('nginx', ['-t']);
  if (!t.ok) {
    if (had) writeFileSync(NGINX_SNIPPET, old, 'utf-8');
    return { ok: false, err: 'nginx test failed: ' + t.err.slice(0, 300) };
  }
  const r = await run('systemctl', ['reload', 'nginx']);
  return { ok: r.ok, err: r.ok ? '' : r.err.slice(0, 300) };
}

// Find films by title words or TMDB id (for the admin search box).
export async function searchMovies(q: string) {
  const s = (q || '').trim();
  let where: string;
  if (/^\d{1,9}$/.test(s)) {
    where = `tmdb_id = ${Number(s)}`;
  } else {
    const words = s.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim().split(' ').filter(Boolean).slice(0, 6);
    if (!words.length) return [];
    where = words.map((w) => `lower(title) LIKE '%${w}%'`).join(' AND ');
  }
  const r = await sql(
    `SELECT m.id, m.tmdb_id, m.title, m.year,
       (SELECT count(*) FROM download_links d WHERE d.content_type='movie' AND d.content_id=m.id AND d.is_active) AS active_links
     FROM movies m WHERE ${where} ORDER BY m.year DESC NULLS LAST, m.title LIMIT 25`
  );
  if (!r.ok) return [];
  const taken = takenDownIds();
  return r.rows.map((c) => ({
    id: Number(c[0]), tmdb_id: Number(c[1]), title: c[2], year: c[3] ? Number(c[3]) : null,
    active_links: Number(c[4]), taken_down: taken.has(Number(c[1])),
  }));
}

// THE TAKEDOWN. One click does everything.
export async function takeDown(tmdbId: number, note: string) {
  if (!Number.isInteger(tmdbId) || tmdbId <= 0) return { ok: false, error: 'Bad TMDB id' };
  const mv = await sql(`SELECT id, title, year FROM movies WHERE tmdb_id = ${tmdbId} ORDER BY id`);
  if (!mv.ok || !mv.rows.length) return { ok: false, error: 'No film with that TMDB id' };
  const ids = mv.rows.map((c) => Number(c[0]));
  const title = mv.rows[0][1];
  const year = mv.rows[0][2] ? Number(mv.rows[0][2]) : null;
  const idList = ids.join(',');

  // every file id tied to this film, including ones already switched off
  const f = await sql(
    `SELECT telegram_file_id FROM download_links WHERE content_type='movie' AND content_id IN (${idList}) AND telegram_file_id ~ '^[0-9]+$'
     UNION SELECT telegram_file_id FROM subtitle_links WHERE content_type='movie' AND content_id IN (${idList}) AND telegram_file_id ~ '^[0-9]+$'`
  );
  if (!f.ok) return { ok: false, error: 'Could not read the file list: ' + f.err };
  const files = f.rows.map((c) => c[0]);

  // 1) list first (so the page + engine block it even if a later step hiccups)
  const list = readTakedowns().filter((e) => Number(e.tmdb_id) !== tmdbId);
  const prev = readTakedowns().find((e) => Number(e.tmdb_id) === tmdbId);
  const merged = Array.from(new Set([...(prev?.files || []), ...files]));
  list.push({ tmdb_id: tmdbId, title, year, key: titleKey(title), files: merged, note: (note || '').slice(0, 300), added: prev?.added || new Date().toISOString() });
  writeTakedowns(list);

  // 2) switch off every link and subtitle
  const off = await sql(
    `UPDATE download_links SET is_active=false WHERE content_type='movie' AND content_id IN (${idList}) AND is_active;
     UPDATE subtitle_links SET is_active=false WHERE content_type='movie' AND content_id IN (${idList}) AND is_active;
     UPDATE movies SET has_downloads=false WHERE id IN (${idList});`
  );

  // 3) nginx 410 for the files
  const ng = await applyNginx(list);

  // 4) is there a saved stream copy? (reported, never deleted by this tool)
  let cached = 0;
  for (const id of merged) if (existsSync(`/opt/trendimovies/cache/streams/${id}.bin`)) cached++;

  return {
    ok: off.ok && ng.ok,
    title, year, files: merged.length, cached_copies: cached,
    links_off: off.ok, nginx_ok: ng.ok,
    error: [off.ok ? '' : 'Links: ' + off.err, ng.ok ? '' : 'nginx: ' + ng.err].filter(Boolean).join(' | '),
  };
}

// Take a film OFF the list (page and nginx open up again; the engine may link it again on its next run).
// Links that were switched off are NOT switched back on here; that stays a deliberate manual step.
export async function restore(tmdbId: number) {
  const all = readTakedowns();
  const list = all.filter((e) => Number(e.tmdb_id) !== tmdbId);
  if (list.length === all.length) return { ok: false, error: 'Not on the list' };
  writeTakedowns(list);
  const ng = await applyNginx(list);
  return { ok: ng.ok, error: ng.err };
}
